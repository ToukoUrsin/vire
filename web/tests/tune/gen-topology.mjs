#!/usr/bin/env bun
// Writes src/tune/topology.ts: the face-mesh connection lists (copied out of @mediapipe/tasks-vision so the stage
// bundle does not load the 156 KB vision bundle just for constants) and a built-in neutral face
// (MediaPipe's canonical face model, Apache 2.0, plus synthetic iris points).
//   bun tests/tune/gen-topology.mjs /path/to/canonical_face_model.obj
// The .obj is https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
import { readFileSync, writeFileSync } from 'node:fs'
import { FaceLandmarker as F } from '../../node_modules/@mediapipe/tasks-vision/vision_bundle.mjs'

const obj = readFileSync(process.argv[2], 'utf8')
const v = obj.split('\n').filter((l) => l.startsWith('v ')).map((l) => l.trim().split(/\s+/).slice(1).map(Number))
if (v.length !== 468) throw new Error('expected 468 vertices, got ' + v.length)
// canonical: x to the image right, y up, z towards the viewer (cm). Image convention: y down, z away from the camera.
let pts = v.map(([x, y, z]) => [x, -y, -z])
const mid = (ids) => ids.reduce((s, i) => [s[0] + pts[i][0] / ids.length, s[1] + pts[i][1] / ids.length, s[2] + pts[i][2] / ids.length], [0, 0, 0])
const iris = (ids) => {
  const c = mid(ids)
  c[2] += 0.25 // the eyeball sits a little behind the lids
  const r = 0.56
  return [c, [c[0] + r, c[1], c[2]], [c[0], c[1] - r, c[2]], [c[0] - r, c[1], c[2]], [c[0], c[1] + r, c[2]]]
}
pts = pts.concat(iris([33, 133, 159, 145]), iris([362, 263, 386, 374]))
const w = Math.hypot(pts[454][0] - pts[234][0], pts[454][1] - pts[234][1], pts[454][2] - pts[234][2])
const cx = (pts[454][0] + pts[234][0]) / 2
const cy = (pts[10][1] + pts[152][1]) / 2
const cz = (pts[454][2] + pts[234][2]) / 2
const neutral = pts.flatMap(([x, y, z]) => [Math.round(((x - cx) / w) * 1000), Math.round(((y - cy) / w) * 1000), Math.round(((z - cz) / w) * 1000)])

const edges = (list) => {
  const seen = new Set()
  const out = []
  for (const e of list) {
    const a = Math.min(e.start, e.end)
    const b = Math.max(e.start, e.end)
    const k = a * 1000 + b
    if (a === b || seen.has(k)) continue
    seen.add(k)
    out.push(a, b)
  }
  return out
}
const tris = []
for (let i = 0; i + 2 < F.FACE_LANDMARKS_TESSELATION.length; i += 3) {
  const t = F.FACE_LANDMARKS_TESSELATION
  tris.push(t[i].start, t[i + 1].start, t[i + 2].start)
}
const row = (name, arr, doc) => `/** ${doc} */\nexport const ${name}: readonly number[] = [${arr.join(',')}]\n`
const out = `// Generated by tests/tune/gen-topology.mjs. Do not edit by hand.
// Connection lists are MediaPipe's (FaceLandmarker.FACE_LANDMARKS_*), copied here so drawing a face does not
// pull the vision bundle. NEUTRAL is MediaPipe's canonical face model (Apache 2.0) with synthetic iris points.

${row('TESS', edges(F.FACE_LANDMARKS_TESSELATION), 'tessellation edges, flat pairs of landmark indices (' + edges(F.FACE_LANDMARKS_TESSELATION).length / 2 + ' edges)')}
${row('TRIS', tris, 'tessellation triangles, flat triples (' + tris.length / 3 + ' triangles)')}
${row('OVAL', edges(F.FACE_LANDMARKS_FACE_OVAL), 'face outline')}
${row('LIPS', edges(F.FACE_LANDMARKS_LIPS), 'outer and inner lip lines')}
${row('EYES', edges([...F.FACE_LANDMARKS_LEFT_EYE, ...F.FACE_LANDMARKS_RIGHT_EYE]), 'both eye outlines')}
${row('BROWS', edges([...F.FACE_LANDMARKS_LEFT_EYEBROW, ...F.FACE_LANDMARKS_RIGHT_EYEBROW]), 'both eyebrows')}
${row('NEUTRAL', neutral, '478 x,y,z triples of a neutral face: y down, z away from the viewer, one scale on all axes, face width = 1000, centred')}
`
writeFileSync(new URL('../../src/tune/topology.ts', import.meta.url), out)
console.log('wrote topology.ts', out.length, 'bytes; v33.x', pts[33][0].toFixed(2), 'v263.x', pts[263][0].toFixed(2), 'tris', tris.length / 3)
